let LANG = (() => {
  try { const l = JSON.parse(localStorage.getItem('kp.lang')); if (l && LANGS[l]) return l; } catch { /* ignore */ }
  return 'he';
})();

function t(key, vars) {
  let s = (I18N[LANG] && I18N[LANG][key]) ?? I18N.he[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split('{' + k + '}').join(v);
  return s;
}

// מחיל את השפה על כל האלמנטים המסומנים ב-HTML
function applyI18n() {
  const L = LANGS[LANG];
  document.documentElement.lang = LANG;
  document.documentElement.dir = L.dir;
  document.querySelectorAll('[data-i18n]').forEach((e) => { e.textContent = t(e.dataset.i18n); });
  document.querySelectorAll('[data-i18n-ph]').forEach((e) => { e.placeholder = t(e.dataset.i18nPh); });
  document.querySelectorAll('[data-i18n-title]').forEach((e) => {
    const s = t(e.dataset.i18nTitle);
    e.title = s;
    e.setAttribute('aria-label', s);
  });
  // חץ "חזרה" לפי כיוון השפה
  document.querySelectorAll('.back-arrow').forEach((e) => { e.textContent = L.dir === 'rtl' ? '→' : '←'; });
  document.querySelectorAll('select.lang-select').forEach((s) => { s.value = LANG; });
}

function setLang(l) {
  if (!LANGS[l]) return;
  LANG = l;
  try { localStorage.setItem('kp.lang', JSON.stringify(l)); } catch { /* ignore */ }
  applyI18n();
}

function langSelect() {
  const s = document.createElement('select');
  s.className = 'lang-select';
  s.setAttribute('aria-label', 'Language');
  for (const [code, info] of Object.entries(LANGS)) {
    const o = document.createElement('option');
    o.value = code;
    o.textContent = info.name;
    s.append(o);
  }
  s.value = LANG;
  return s;
}
